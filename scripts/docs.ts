/** Builds SOURCES.md and ASSUMPTIONS.md from the code, so the docs can't drift from the numbers used. */
import { ECONOMIC, SHOCK_CORRELATION, EQUITY_TAIL_DF } from '../assumptions/economic';
import { LATEST_RULES, SCHEDULED_CHANGES, SOURCES } from '../rules';
import { ruleEntries } from '../rules/catalogue';
import type { SourceRef } from '../rules/schema';

const fmt = (unit: string, v: number) =>
  unit === 'percent' ? `${+(v * 100).toFixed(3)}%` : unit === 'pp' ? `${+(v * 100).toFixed(3)} pts` : unit === 'years' ? `${v} years` : String(v);
const refs = (rs: SourceRef[]) => rs.map((r) => `[${SOURCES[r.id].title}](${SOURCES[r.id].url})`).join('; ');
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function sourcesMarkdown(): string {
  const lines = [
    '# Sources',
    '',
    '<!-- Generated by `npm run docs` from rules/sources.ts. Do not edit by hand. -->',
    '',
    'Every external source RichCalc relies on. Primary sources (GOV.UK, HMRC, legislation.gov.uk, gov.scot, gov.wales, ONS, Bank of England) are preferred.',
    '',
    '| Source | Publisher | Kind | Accessed |',
    '|---|---|---|---|',
  ];
  for (const s of Object.values(SOURCES).sort((a, b) => a.publisher.localeCompare(b.publisher))) {
    lines.push(`| [${cell(s.title)}](${s.url}) | ${cell(s.publisher)} | ${s.kind} | ${s.accessed} |`);
  }
  return lines.join('\n') + '\n';
}

export function assumptionsMarkdown(): string {
  const lines = [
    '# Assumptions',
    '',
    '<!-- Generated by `npm run docs` from assumptions/economic.ts and rules/. Do not edit by hand. -->',
    '',
    'Status key: **confirmed** = published figure taken directly; **announced** = government announcement for a future date;',
    '**convention** = market practice rather than a rule; **judgement** = our modelling choice (reason given);',
    '**unverified** = a widely quoted figure we could not check against the primary source (shown with a badge in the UI).',
    '',
    '## Flagged for follow-up',
    '',
  ];
  const flagged = Object.values(ECONOMIC).filter((a) => a.status === 'unverified');
  for (const a of flagged) lines.push(`- **${a.label}** (${fmt(a.unit, a.value)}): ${a.note}`);
  lines.push(
    '- **Volatility and persistence parameters** for inflation and Bank Rate are judgement, pending a formal fit to ONS CPI (series D7G7) and Bank of England Bank Rate history. The calibration needs those datasets, which our research environment could not download.',
    '',
    '## Economic assumptions (editable in each tool)',
    '',
    '| Assumption | Default | Plausible range | Status | Why | Source |',
    '|---|---|---|---|---|---|',
  );
  for (const a of Object.values(ECONOMIC)) {
    lines.push(
      `| ${cell(a.label)} (\`${a.key}\`) | ${fmt(a.unit, a.value)} | ${fmt(a.unit, a.range.low)} to ${fmt(a.unit, a.range.high)} | ${a.status} | ${cell(a.note ?? '')} | ${refs(a.source)} |`,
    );
  }
  lines.push(
    '',
    '### Distributions',
    '',
    `- Inflation: mean-reverting (AR(1)) surprises around a central path that fades from the 12-month value to the long-run rate.`,
    `- Bank Rate: mean-reverting towards long-run inflation plus a real margin; responds to inflation surprises; floored at 0%.`,
    `- Shares: log real returns with a Student-t shock (${EQUITY_TAIL_DF} degrees of freedom), scaled to the stated volatility.`,
    `- Bonds: log real returns with a normal shock.`,
    `- Correlations between yearly shocks (inflation, rate, shares, bonds): ${JSON.stringify(SHOCK_CORRELATION.matrix)}. ${SHOCK_CORRELATION.note}`,
    '',
    `## Tax rules: ${LATEST_RULES.taxYear} (rules/${LATEST_RULES.id}.ts)`,
    '',
    '| Rule | Value | Status | Verified | Note | Source |',
    '|---|---|---|---|---|---|',
  );
  for (const r of ruleEntries(LATEST_RULES)) {
    lines.push(`| ${cell(r.label)} | ${cell(r.value)} | ${r.sourced.status} | ${r.sourced.verified} | ${cell(r.sourced.note ?? '')} | ${refs(r.sourced.source)} |`);
  }
  lines.push('', '## Announced changes applied from their effective dates', '');
  for (const c of SCHEDULED_CHANGES) lines.push(`- **${c.effectiveFrom}** (${c.status}): ${c.summary} Source: ${refs(c.source)}.`);
  lines.push(
    '',
    '## Modelling choices',
    '',
    '- Both options in a comparison have identical cash outflows each month; only where the money goes differs.',
    '- Overpayers keep the same monthly payment at each remortgage and take a shorter term.',
    '- Overpayments never exceed the yearly allowance, so early repayment charges are never paid; the excess is invested.',
    '- Lower rates for a lower loan-to-value are not modelled (this slightly understates the benefit of overpaying).',
    '- Spare cash is constant in pounds. Results are deflated to today’s money with each simulated future’s inflation.',
    '- Tax rules beyond those announced are held at their last known values.',
  );
  return lines.join('\n') + '\n';
}

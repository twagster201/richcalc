/**
 * Default assumptions for the shared economic scenario generator, and costs used by the tools.
 *
 * Status meanings: 'confirmed' = a published figure taken directly; 'judgement' = a modelling
 * choice anchored on the cited source; 'convention' = market practice; 'unverified' = a widely
 * quoted figure we could not check against the primary source (shown with a badge in the UI).
 */
import type { Assumption, AssumptionSet } from './types';
import type { SourceId } from '../rules/sources';
import type { Status } from '../rules/schema';

const VERIFIED = '2026-10-10';

function a(
  key: string,
  fields: Omit<Assumption, 'key' | 'source' | 'verified' | 'status'> & { sources: SourceId[]; status: Status },
): Assumption {
  const { sources, ...rest } = fields;
  return { key, ...rest, source: sources.map((id) => ({ id })), verified: VERIFIED };
}

